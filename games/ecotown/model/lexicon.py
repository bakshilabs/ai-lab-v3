"""Hand-written lexicon for the Plotter synthetic dataset.

Each level has:
  slots[slot] = {
     "adj":  attributive modifiers, used in noun phrases ("dry, sunny land"),
     "pred": predicative phrases, used after "is/be" ("make sure the land is dry");
             defaults to "adj" when the level sets PRED_FROM_ADJ,
     "np":   noun phrases ("high ground", "no cars"),
     "cl":   imperative clauses ("keep the meadow wild", "don't cut the hedges"),
     "sfx":  suffixes glued onto another fragment ("... for the bees").
  }
  combos:  fragments that express several slots at once.
  np_adj:  noun-phrase templates taking the joined adjectives ({A}).
  generic_np / generic: on-topic text with no slot (all labels 0).
  anti:    on-topic clauses that must NOT fire a slot (contrast for negation:
           "cut the hedges" vs "don't cut the hedges").
  frames:  level-specific sentence frames (see gen_data.py for placeholders).

Placeholders inside fragments: {N} a number, {MIN} "minutes"/"mins"/"min".
Nothing in sanity_child.json is copied here; that list is a held-out check.
"""


def neg(objs, verbs, pre=("don't", "do not", "please don't", "never", "dont")):
    """'don't cut the hedges', 'do not chop down the trees', ..."""
    return [f"{p} {v} the {o}" for p in pre for v in verbs for o in objs]


def keep(objs, verbs=("keep", "protect", "save", "leave alone", "look after", "keep safe")):
    out = []
    for v in verbs:
        for o in objs:
            if v == "leave alone":
                out.append(f"leave the {o} alone")
            elif v == "keep safe":
                out.append(f"keep the {o} safe")
            else:
                out.append(f"{v} the {o}")
    return out


